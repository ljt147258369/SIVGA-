# □ 部署日志 pip 清单 = requirements.txt 逐行一致
#   （日志格式：Successfully installed streamlit-x.x openai-x.x ...）；
# □ 改 title 文案 → push → 记录 redeploy 耗时（通常 1-3 分钟）→
#   线上生效截图。
#
# 观察答案：④ 对账——日志里每个包都应能在 requirements.txt 找到
