# 练习 2 · 密钥三方案裁定（参考答案）
#
# ① 能正常跑的：只有 C。A「能跑但当天就会被扫」；B 能跑但同样泄漏。
#    泄漏速度：GitHub 公开提交会在**分钟级**内被自动扫描机器人抓到
#    （关键词 sk- 模式匹配），然后拿去刷接口烧你的额度。DeepSeek 平台
#    检测到异常也可能封 key。真发生过：无数公开仓库的 key 几小时内
#    产生几千美元调用账单。
# ② 删文件补救不了：git 保存的是**提交历史**——.env 曾在某次 commit 里，
#    历史里永远查得到（git log/git show 旧提交照样翻出 key）。
#    GitHub 甚至缓存旧提交对象。删文件只删了「最新版本」，没删「历史」。
# ③ 唯一有效补救：**立刻作废这个 key**（平台后台删除/重置），
#    换新 key，新 key 只走 C 的两条通道。泄漏过的 key 视为永久公开。
#    （顺带：付费平台会直接按泄漏处理自动吊销，但别赌它。）

