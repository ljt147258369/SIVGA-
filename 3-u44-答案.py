# □ git status 输出里没有 .env（.gitignore 生效铁证）
#   ——若出现 .env：检查 .gitignore 是否在仓库根目录、拼写是否正确；
#     若已经 commit 过 .env，需先 git rm --cached .env 再 commit
#     （并按练习 2③ 立刻换 key，因为已进历史）。
